import pandas as pd

a=pd.read_csv("Titanic-Dataset.csv")

b=pd.DataFrame(a)

#Display only columns: Name, Sex, Age, Fare, Survived
b[["Name","Sex","Age","Fare", "Survived"]]

#B. Select passengers who:
#Are female
b[b["Sex"]=="female"]

#Fare > 30
b[b["Fare"]>30]

b

#C. Group by Pclass and compute:
# Survival rate
b.groupby("Pclass")["Survived"].mean()

#Average Fare
b.groupby("Pclass")["Fare"].mean()

#Average Age
b.groupby("Pclass")["Age"].mean()

