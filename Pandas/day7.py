import pandas as pd

name=["A","B","C","D"]
age=[12,34,56,76]
sal=[1000,2000,3000,4000]
department=["HR","Analysis","HR","IT"]
data={"NAME":name,"AGE":age,"SAL":sal,"DEPT":department}
df=pd.DataFrame(data)
print(df)

df.groupby("DEPT")#object address .in group by we always need too use aggregation function.

df[(df["AGE"]==66) & (df["DEPT"]=="HR")]

df[(df["AGE"]==66) | (df["DEPT"]=="HR")]

df.groupby("DEPT")["SAL"].value_counts()

df.groupby("DEPT")["SAL"].sum()

df.groupby("DEPT")["SAL"].mean()

df.groupby("DEPT")["SAL"].count()

df.groupby("DEPT")["SAL"].agg(["mean","sum","count"])



