import pandas as pd

df1=pd.DataFrame({"ID":[1,2,3,4,5],"NAME":["Bhaki","Vidhi","C","D","E"]})
df2=pd.DataFrame({"ID":[7,2,3,4,9],"MARKS":[32,46,77,87,89]})
res1=pd.merge(df1,df2,on="ID",how="inner")
res1

res=pd.merge(df1,df2,on="ID",how="left")
res

res2=pd.merge(df1,df2,on="ID",how="right")
res2

res=pd.merge(df1,df2,on="ID",how="outer")
res

